/// <summary>
/// What translating a specification produced.
/// </summary>
/// <param name="ClassName">Name of the generated class.</param>
/// <param name="Source">The C# source.</param>
/// <param name="SourceHash">
/// What the candidate is identified by: the hash of the same source emitted without the name and the
/// thesis, so that two specifications differing only in their wording are one strategy.
/// </param>
/// <param name="Indicators">Indicators the strategy will maintain, by the field name it holds them in.</param>
public sealed record TranslatedStrategy(
	string ClassName,
	string Source,
	string SourceHash,
	IReadOnlyDictionary<string, string> Indicators);

/// <summary>
/// Turns a checked specification into a StockSharp strategy.
/// </summary>
/// <remarks>
/// The output is an ordinary <c>Strategy</c>, of the same shape as one written by hand: parameters
/// declared through <c>Param</c> with their optimisation ranges, indicators created in
/// <c>OnStarted2</c>, a candle subscription, and orders placed with <c>BuyMarket</c> and
/// <c>SellMarket</c>. That matters beyond tidiness — a candidate that survives research is then a
/// strategy anyone can take away and run in Runner, Shell or Designer, rather than something that only
/// works inside this tool.
///
/// It is a compiler rather than a generator: the same specification always produces the same source,
/// byte for byte, which is what lets a candidate be identified by the hash of its source and a result be
/// re-derived later.
///
/// The name and the thesis are written into the source because the file is meant to be read, but the
/// identity is taken over the source without them: a candidate is what it does, and rewording a
/// sentence must not spend one of the candidates a project is allowed.
/// </remarks>
public static class StrategyTranslator
{
	/// <summary>Version of the translator, which is part of what a candidate is.</summary>
	public const string Version = "2.4.0";

	// Stands in for the generated class name while the identity is being taken, so that a strategy
	// renamed is not a strategy rewritten.
	private const string IdentityClassName = "GeneratedStrategy";

	private static readonly IReadOnlyDictionary<string, string> _indicatorTypes =
		new Dictionary<string, string>(StringComparer.Ordinal)
		{
			["sma"] = "SimpleMovingAverage",
			["ema"] = "ExponentialMovingAverage",
			["rsi"] = "RelativeStrengthIndex",
			["highest"] = "Highest",
			["lowest"] = "Lowest",
			["stdDev"] = "StandardDeviation",
			["atr"] = "AverageTrueRange",
			["volumeSma"] = "SimpleMovingAverage",
		};

	/// <summary>
	/// Translates a specification.
	/// </summary>
	/// <param name="spec">Specification to translate. It must already have been checked.</param>
	/// <returns>The generated strategy.</returns>
	/// <exception cref="InvalidOperationException">The specification would not survive translation.</exception>
	public static TranslatedStrategy Translate(StrategySpec spec)
	{
		ArgumentNullException.ThrowIfNull(spec);

		var validation = SpecValidator.Validate(spec);

		if (!validation.IsValid)
		{
			// Translating an unchecked specification would turn a clear refusal into a compiler error, or
			// worse into code that runs and means something other than what was written.
			throw new InvalidOperationException(
				"Only a checked specification can be translated. Unresolved: " +
				string.Join("; ", validation.Problems.Select(p => $"{p.Path}: {p.Message}")));
		}

		var indicators = CollectIndicators(spec);
		var className = ClassNameOf(spec.Name);
		var source = Emit(spec, className, indicators, prose: true);

		// The identity is taken over the same emission with the wording left out: the class name replaced
		// by a fixed one and the two documentation lines dropped. Every rule, parameter and limit still
		// reaches the hash, so the only difference it stops seeing is the one that changes nothing.
		var identity = Emit(spec, IdentityClassName, indicators, prose: false);

		return new(
			className,
			source,
			Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(identity))),
			indicators.ToDictionary(i => i.Field, i => i.Name, StringComparer.Ordinal));
	}

	private static string Emit(
		StrategySpec spec,
		string className,
		IReadOnlyList<Indicator> indicators,
		bool prose)
	{
		var code = new CodeWriter();
		var offsets = Offsets(spec, indicators);

		code.Line($"// Generated by the Odysseus translator {Version}.");
		code.Line("// Every rule below carries the identifier it has in the specification, so the two can be");
		code.Line("// read side by side. Do not edit: the next translation of the same specification would");
		code.Line("// produce this file again and lose the edit.");
		code.Blank();
		code.Line("namespace Odysseus.Generated;");
		code.Blank();
		code.Line("using System;");
		code.Line("using System.Collections.Generic;");
		code.Line("using System.Linq;");
		code.Blank();
		code.Line("using Ecng.Common;");
		code.Blank();
		code.Line("using StockSharp.Algo.Indicators;");
		code.Line("using StockSharp.Algo.Strategies;");
		code.Line("using StockSharp.BusinessEntities;");
		code.Line("using StockSharp.Messages;");
		code.Blank();

		if (prose)
		{
			code.Line($"/// <summary>{Escape(spec.Name)}</summary>");
			code.Line($"/// <remarks>{Escape(spec.Thesis)}</remarks>");
		}

		code.Line($"public class {className} : Strategy");
		code.Open();

		EmitFields(code, spec, indicators, offsets);
		code.Blank();
		EmitProperties(code, spec);
		code.Blank();
		EmitConstructor(code, spec, className);
		code.Blank();
		EmitMarketClock(code);
		code.Blank();
		EmitWorkingSecurities(code);
		code.Blank();
		EmitReset(code, indicators, offsets);
		code.Blank();
		EmitStarted(code, indicators);
		code.Blank();
		EmitOwnTrade(code);
		code.Blank();
		EmitProcess(code, spec, indicators, offsets);

		if (offsets.Count > 0)
		{
			code.Blank();
			EmitSeries(code);
		}

		code.Close();

		return code.ToString();
	}

	private static void EmitFields(
		CodeWriter code,
		StrategySpec spec,
		IReadOnlyList<Indicator> indicators,
		IReadOnlyDictionary<string, int> offsets)
	{
		foreach (var parameter in spec.Parameters)
			code.Line($"private readonly StrategyParam<{TypeOf(parameter.Type)}> _{Camel(parameter.Name)};");

		code.Line("private readonly StrategyParam<DataType> _candleType;");
		code.Line("private readonly StrategyParam<TimeSpan> _sessionEnd;");
		code.Line("private readonly StrategyParam<int> _entryDelayBars;");
		code.Blank();

		code.Line("// The limits the specification declared. The host sizes the position from the first of");
		code.Line("// them, so a strategy that risks a quarter of the account and one that risks a tenth are");
		code.Line("// two strategies; carrying the numbers here is what makes the source say so.");
		code.Line($"public const decimal MaxPositionPercent = {Literal(spec.Risk.MaxPositionPercent, ParameterTypes.Decimal)};");
		code.Line($"public const decimal MaxDailyLossPercent = {Literal(spec.Risk.MaxDailyLossPercent, ParameterTypes.Decimal)};");
		code.Blank();

		code.Line("// Bars carry UTC. Every time of day in the specification is written on the clock the");
		code.Line("// market keeps, and the offset between the two changes twice a year, so a bar is");
		code.Line("// converted at the moment it arrived rather than by a fixed number of hours.");
		code.Line("private static readonly TimeZoneInfo _market = MarketZone();");
		code.Blank();

		foreach (var indicator in indicators)
			code.Line($"private {_indicatorTypes[indicator.Name]} {indicator.Field};");

		foreach (var (name, size) in offsets.OrderBy(o => o.Key, StringComparer.Ordinal))
			code.Line($"private Series {name};");

		code.Blank();
		code.Line("// A signalled entry that has not been placed yet: which way, and how many candles are");
		code.Line("// left before it is. Zero delay never uses them.");
		code.Line("private int _armedSide;");
		code.Line("private int _armedDelay;");
		code.Blank();
		code.Line("// A finished candle that arrived before the clock had passed the moment it closed, kept");
		code.Line("// until it has.");
		code.Line("private ICandleMessage _heldCandle;");
		code.Blank();
		code.Line("private decimal _entryPrice;");
		code.Line("private decimal _entryVolume;");
		code.Line("private Sides? _entrySide;");
		code.Line("private int _barsHeld;");
		code.Line("private int _barsSeen;");
		code.Line("private DateTime _marketDay;");
		code.Line("private decimal _dayOpenPnL;");
	}

	private static void EmitProperties(CodeWriter code, StrategySpec spec)
	{
		foreach (var parameter in spec.Parameters)
		{
			code.Line($"/// <summary>{Escape(parameter.Name)}.</summary>");
			code.Line($"public {TypeOf(parameter.Type)} {parameter.Name}");
			code.Open();
			code.Line($"get => _{Camel(parameter.Name)}.Value;");
			code.Line($"set => _{Camel(parameter.Name)}.Value = value;");
			code.Close();
			code.Blank();
		}

		code.Line("/// <summary>Candles the rules are evaluated on.</summary>");
		code.Line("public DataType CandleType");
		code.Open();
		code.Line("get => _candleType.Value;");
		code.Line("set => _candleType.Value = value;");
		code.Close();
		code.Blank();

		code.Line("/// <summary>Time of day the session ends, where the market is.</summary>");
		code.Line("public TimeSpan SessionEnd");
		code.Open();
		code.Line("get => _sessionEnd.Value;");
		code.Line("set => _sessionEnd.Value = value;");
		code.Close();
		code.Blank();

		code.Line("/// <summary>Candles between an entry signal and the order it produces.</summary>");
		code.Line("public int EntryDelayBars");
		code.Open();
		code.Line("get => _entryDelayBars.Value;");
		code.Line("set => _entryDelayBars.Value = value;");
		code.Close();
	}

	private static void EmitConstructor(CodeWriter code, StrategySpec spec, string className)
	{
		code.Line("/// <summary>Declares the parameters and the ranges the optimiser may search.</summary>");
		code.Line($"public {className}()");
		code.Open();

		foreach (var parameter in spec.Parameters)
		{
			var literal = Literal(parameter.Default, parameter.Type);

			code.Line($"_{Camel(parameter.Name)} = Param(nameof({parameter.Name}), {literal})");
			code.Indented($".SetDisplay(\"{Escape(parameter.Name)}\", \"Declared by the specification.\", \"Parameters\")");

			if (parameter.Optimizable)
			{
				code.Indented(
					$".SetOptimize({Literal(parameter.Minimum, parameter.Type)}, " +
					$"{Literal(parameter.Maximum, parameter.Type)}, {Literal(parameter.Step, parameter.Type)});");
			}
			else
			{
				code.Indented(";");
			}

			code.Blank();
		}

		code.Line($"_candleType = Param(nameof(CandleType), TimeSpan.FromSeconds({(int)spec.TimeFrame.TotalSeconds}).TimeFrame())");
		code.Indented(".SetDisplay(\"Candle type\", \"Candles the rules are evaluated on.\", \"Data\");");
		code.Blank();

		// The exchange calendar is not available to a strategy, so the close is a parameter rather than a
		// guess. Its default is the close of the American session on the clock that market keeps, which is
		// the clock every other time in the specification is written on.
		code.Line("_sessionEnd = Param(nameof(SessionEnd), new TimeSpan(16, 0, 0))");
		code.Indented(".SetDisplay(\"Session end\", \"Time of day the session ends, where the market is.\", \"Data\");");

		code.Blank();

		// Not part of the hypothesis: the rules are the same whether the fill is instant or a candle late.
		// It is here so a run can ask what the result looks like without the assumption of being fast.
		code.Line("_entryDelayBars = Param(nameof(EntryDelayBars), 0)");
		code.Indented(".SetDisplay(\"Entry delay\", \"Candles between an entry signal and the order it produces.\", \"Execution\");");

		code.Close();
	}

	private static void EmitMarketClock(CodeWriter code)
	{
		code.Line("/// <summary>The market's own date for a moment, which is not the machine's.</summary>");
		code.Line("/// <param name=\"time\">Moment the bar opened, in UTC.</param>");
		code.Line("/// <returns>The date where the market is.</returns>");
		code.Line("private static DateTime MarketDate(DateTime time)");
		code.Indented("=> TimeZoneInfo.ConvertTimeFromUtc(DateTime.SpecifyKind(time, DateTimeKind.Utc), _market).Date;");
		code.Blank();

		code.Line("/// <summary>Time of day where the market is.</summary>");
		code.Line("/// <param name=\"time\">Moment the bar opened, in UTC.</param>");
		code.Line("/// <returns>The time of day on the market's own clock.</returns>");
		code.Line("private static TimeSpan MarketTime(DateTime time)");
		code.Indented("=> TimeZoneInfo.ConvertTimeFromUtc(DateTime.SpecifyKind(time, DateTimeKind.Utc), _market).TimeOfDay;");
		code.Blank();

		code.Line("// Both names for the same zone: the first is what every platform but Windows calls it,");
		code.Line("// the second is what Windows called it before it learned the first.");
		code.Line("private static TimeZoneInfo MarketZone()");
		code.Open();
		code.Line("try");
		code.Open();
		code.Line("return TimeZoneInfo.FindSystemTimeZoneById(\"America/New_York\");");
		code.Close();
		code.Line("catch (TimeZoneNotFoundException)");
		code.Open();
		code.Line("return TimeZoneInfo.FindSystemTimeZoneById(\"Eastern Standard Time\");");
		code.Close();
		code.Close();
	}

